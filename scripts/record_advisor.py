#!/usr/bin/env python3
"""Records an open-weight advisor's raw answers for the cognitive evaluation (T172, SR-K7).

    LARIS_MODEL_SERVICE__CHAT_MODEL_ID=DIR python scripts/record_advisor.py \\
        --config configs/cognitive-eval.json --name NAME --out RAW.json

It asks the chat backend of the model service (``OpenWeightChat``, inference only: no gradient, no
optimiser, no training) the questions of the configuration, asks it to reword each claim and to
propose a claim with an exact quote for each question, and writes what it said. Every ``supported``
and ``faithful`` label is left ``null``: a person reads each entry against the accepted claims and
fills the labels before the file goes to ``cognitive_eval --advisors``. Nothing is generated by any
other model, and the raw file records the model id, decoding settings and prompts.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

ANSWER = "Answer the question briefly, in one or two sentences."
REWORD = (
    "Reword the following sentence without changing its meaning. Reply with the reworded "
    "sentence only.\n\nSentence: {claim}"
)
PROPOSE = (
    "Source text:\n{source}\n\nQuestion: {question}\n\nPropose one claim that answers the question "
    "and quote, word for word, the part of the source text that supports it. Reply with JSON only: "
    '{{"statement": "...", "quote": "..."}}'
)


def ask(provider: Any, prompt: str, system: str | None = None) -> str:
    messages = [{"role": "user", "content": prompt}]
    if system:
        messages.insert(0, {"role": "system", "content": system})
    turn = provider.chat(messages, [])
    return (turn.content or "").strip()


def parse_proposal(text: str) -> dict[str, str]:
    match = re.search(r"\{.*\}", text, flags=re.DOTALL)
    try:
        value = json.loads(match.group(0)) if match else {}
    except json.JSONDecodeError:
        value = {}
    return {"statement": str(value.get("statement", "")), "quote": str(value.get("quote", ""))}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--name", required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    if args.out.exists():
        raise SystemExit(f"{args.out} exists; refusing to overwrite a recording")
    config = json.loads(args.config.read_text(encoding="utf-8"))

    from laris.model.inference.open_llm import OpenWeightChat

    provider = OpenWeightChat()
    provider.load()
    cfg = provider.cfg
    source = config["sources"][0]
    replies = {
        q["id"]: {"text": ask(provider, q["text"] + "?", ANSWER), "supported": None}
        for q in config["questions"]
    }
    rewordings = {
        c["id"]: {"text": ask(provider, REWORD.format(claim=c["statement"])), "faithful": None}
        for c in config["claims"]
    }
    proposals = []
    for q in config["questions"]:
        raw = ask(provider, PROPOSE.format(source=source["text"], question=q["text"] + "?"))
        proposals.append(
            {
                **parse_proposal(raw),
                "source": source["title"],
                "supported": None,
                "question": q["id"],
                "raw": raw,
            }
        )
    record = {
        "name": args.name,
        "kind": f"recorded: {cfg.chat_model_id} ({cfg.chat_quantization}), "
        f"temperature {cfg.chat_temperature}, thinking {cfg.chat_thinking}, "
        f"max_new_tokens {cfg.chat_max_new_tokens}",
        "labelled": False,
        "prompts": {"answer": ANSWER, "reword": REWORD, "propose": PROPOSE},
        "replies": replies,
        "rewordings": rewordings,
        "proposals": proposals,
    }
    args.out.write_text(json.dumps(record, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(
        f"recorded {len(replies)} replies, {len(rewordings)} rewordings, {len(proposals)} proposals"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
